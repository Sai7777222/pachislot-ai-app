def main() -> int:
    text = SRC_PATH.read_text(encoding="utf-8")
    applied = []
    for category, user_text, old_a, new_a, reason in FIXES:
        count = text.count(old_a)
        if count != 1:
            raise SystemExit(
                f"[ABORT] category={category} user={user_text!r}: "
                f"old assistant text found {count} times (expected exactly 1). "
                f"old={old_a!r}"
            )
        text = text.replace(old_a, new_a, 1)
        applied.append(
            {
                "category": category,
                "user": user_text,
                "before": old_a,
                "after": new_a,
                "reason": reason,
            }
        )

    SRC_PATH.write_text(text, encoding="utf-8")

    import json

    report_path = SRC_PATH.parent / "reports" / "phase4b_review_fixes_diff.json"
    report_path.write_text(json.dumps(applied, ensure_ascii=False, indent=2), encoding="utf-8")

    d_fixes = sum(1 for a in applied if a["category"] == "D")
    b_fixes = sum(1 for a in applied if a["category"] == "B")
    print(f"D category fixes applied: {d_fixes} / 30")
    print(f"B category fixes applied: {b_fixes} / 70")
    print(f"Diff report written to: {report_path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
