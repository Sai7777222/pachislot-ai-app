def main():
    rows = []
    for mode, plist in [("SMALL_TALK", SMALL_TALK_PROBES), ("PACHISLOT_FACTUAL", PACHISLOT_FACTUAL_PROBES),
                          ("PACHISLOT_CONVERSATIONAL", PACHISLOT_CONVERSATIONAL_PROBES),
                          ("OOD_FACTUAL", OOD_FACTUAL_PROBES)]:
        assert len(plist) == 30, f"{mode} has {len(plist)} probes, expected 30"
        for i, prompt in enumerate(plist, start=1):
            rows.append({"probe_id": f"ZP-{mode[:2]}{i:02d}", "expected_mode": mode, "prompt": prompt,
                         "annotation_source": "human_predefined_before_router_or_generation_2026-08-28",
                         "frozen": True})
    assert len(rows) == 120
    out = {"purpose": "Section7: router accuracy評価用の独立ground truth(120probe)。generation前にfreeze。",
           "total": len(rows), "rows": rows}
    (REPORTS_DIR / "phase4zp_router_ground_truth.json").write_text(
        json.dumps(out, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"wrote {len(rows)} probes")


if __name__ == "__main__":
    main()
